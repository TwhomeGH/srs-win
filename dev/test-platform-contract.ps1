<#
.SYNOPSIS
    Verify the Windows PID-lock capability against the real SRS binary.

.DESCRIPTION
    Starts SRS with an isolated work directory and high ports, then verifies:
      - a second instance cannot acquire the same pid file;
      - a stale pid file does not permanently block startup;
      - normal startup still serves the HTTP API.

    This complements the C++ ctest suite, which cannot easily instantiate the
    server process and exercise LockFileEx end-to-end.

.EXAMPLE
    pwsh dev/test-platform-contract.ps1
    pwsh dev/test-platform-contract.ps1 -SrsExe trunk/ide/srs_msvc/build-full/Debug/srs.exe
#>
[CmdletBinding()]
param(
    [string]$SrsExe = 'trunk/ide/srs_msvc/build/Debug/srs.exe',
    [int]$ApiPort = 20985,
    [int]$RtmpPort = 20935
)

$ErrorActionPreference = 'Stop'
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$SrsExe = (Resolve-Path (Join-Path $repoRoot $SrsExe)).Path
$workDir = Join-Path $repoRoot 'dev/runtime/platform-contract'
$objs = Join-Path $workDir 'objs'
$configPath = Join-Path $workDir 'platform-contract.conf'

New-Item -ItemType Directory $objs -Force | Out-Null
$config = @"
# Generated by dev/test-platform-contract.ps1
max_connections     10;
srs_log_tank        console;
daemon              off;

rtmp {
    listen          $RtmpPort;
}

http_api {
    enabled         on;
    listen          $ApiPort;
}
"@
Set-Content -LiteralPath $configPath -Value $config -Encoding ascii

function Start-Srs([string]$tag) {
    $out = Join-Path $workDir "$tag.out.log"
    $err = Join-Path $workDir "$tag.err.log"
    $process = Start-Process -FilePath $SrsExe `
        -ArgumentList @('-c', $configPath) `
        -WorkingDirectory $workDir `
        -NoNewWindow -PassThru `
        -RedirectStandardOutput $out `
        -RedirectStandardError $err
    return [pscustomobject]@{ Process = $process; Out = $out; Err = $err }
}

function Wait-Api($process) {
    for ($i = 0; $i -lt 40; $i++) {
        Start-Sleep -Milliseconds 250
        $process.Refresh()
        if ($process.HasExited) {
            return $false
        }
        try {
            $response = Invoke-RestMethod -Uri "http://127.0.0.1:$ApiPort/api/v1/versions" -TimeoutSec 2
            if ($response.code -eq 0 -and $response.data.version) {
                return $true
            }
        } catch {
            continue
        }
    }
    return $false
}

function Stop-Srs($process) {
    if ($process -and -not $process.HasExited) {
        Stop-Process -Id $process.Id -Force -ErrorAction SilentlyContinue
        $process.WaitForExit(5000) | Out-Null
    }
}

$first = $null
$second = $null
$stale = $null
try {
    Remove-Item -LiteralPath (Join-Path $objs 'srs.pid') -ErrorAction SilentlyContinue

    Write-Host 'platform contract: start first instance' -ForegroundColor Cyan
    $first = Start-Srs 'first'
    if (-not (Wait-Api $first.Process)) {
        throw "first instance did not serve the API; see $($first.Out) / $($first.Err)"
    }

    Write-Host 'platform contract: second instance must be rejected' -ForegroundColor Cyan
    $second = Start-Srs 'second'
    $second.Process.WaitForExit(5000) | Out-Null
    if (-not $second.Process.HasExited) {
        throw 'second instance stayed running; PID lock is not effective'
    }
    if ($second.Process.ExitCode -eq 0) {
        throw 'second instance exited successfully; PID lock is not effective'
    }
    $secondLog = (Get-Content -LiteralPath $second.Out -Raw -ErrorAction SilentlyContinue) + (Get-Content -LiteralPath $second.Err -Raw -ErrorAction SilentlyContinue)
    if ($secondLog -notmatch 'already running|PidFile|1034|pid') {
        throw "second instance failed without a pid-lock diagnostic; see $($second.Out) / $($second.Err)"
    }
    Write-Host 'PID duplicate rejected.' -ForegroundColor Green

    Write-Host 'platform contract: stale pid must not block restart' -ForegroundColor Cyan
    Stop-Srs $first.Process
    $first = $null
    Set-Content -LiteralPath (Join-Path $objs 'srs.pid') -Value '999999' -Encoding ascii
    $stale = Start-Srs 'stale'
    if (-not (Wait-Api $stale.Process)) {
        throw "stale pid blocked restart; see $($stale.Out) / $($stale.Err)"
    }
    Write-Host 'stale pid recovered.' -ForegroundColor Green
} finally {
    foreach ($item in @($first, $second, $stale)) {
        if ($item) { Stop-Srs $item.Process }
    }
    Remove-Item -LiteralPath (Join-Path $objs 'srs.pid') -ErrorAction SilentlyContinue
}

Write-Host 'platform contract: PASS' -ForegroundColor Green
