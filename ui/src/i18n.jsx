export function makeT(lang) {
  const table = LANGS[lang] || LANGS.zh;
  return (key, vars = {}) => {
    let value = table[key] || key;
    Object.keys(vars).forEach((name) => {
      value = value.replaceAll(`{${name}}`, String(vars[name]));
    });
    return value;
  };
}
